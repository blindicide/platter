#!/usr/bin/env python3
"""Regenerates src/gui/i18n/core_phrases.cpp: the fixed English phrases the core
libraries produce, marked for lupdate (context "core").

Usage: tools/gen_core_phrases.py   (run from the repository root)
Dynamic messages (with numbers/paths) are handled by core_patterns.cpp instead.
"""
import re, subprocess, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
dirs = ["benchmark", "surface", "imaging", "erase", "partitions", "mkfs", "inspect", "storage", "smart", "qualify", "core", "platform"]
files = []
for d in dirs:
    files += sorted((root / "src" / d).rglob("*.cpp"))
files += sorted((root / "include").rglob("*.hpp"))

lit = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
cand = []
for f in files:
    for line in f.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("//") or s.startswith("#include"):
            continue
        for m in lit.finditer(line):
            cand.append(m.group(1))

sql = re.compile(r'\b(SELECT|INSERT|FROM|WHERE|PRAGMA|CREATE TABLE|ON CONFLICT|ORDER BY|VALUES|DELETE FROM|BEGIN|COMMIT|ROLLBACK)\b')
skip_exact = set("APPDATA HOME PATH PLATTER_HISTORY_DB PLATTER_SMARTCTL XDG_DATA_HOME PLATTER CreatePipe FlushFileBuffers GetFileSizeEx ReadFile WriteFile PhysicalDrive KiB MiB GiB TiB PiB EiB FILE YYYY-MM-DDTHH:MM:SSZ MATCH MISMATCH".split())
skip_exact |= {"begin migration","commit migration","configure database","create meta","create schema v1","delete session","find session",
    "insert session","list devices","list sessions","load session","prepare delete","prepare device upsert","prepare devices","prepare find",
    "prepare list","prepare load","prepare session insert","read schema version","set version","upsert device","empty argv","pipe failed",
    "sudo /opt/platter/platter-helper","platter-helper pid 1234 (root)","WD-W***********","WD-WCC6Y1234567","OK, 14.20 GB, zstd",
    "PASS, 2 passes, 118.4 MB/s","offset size name value","EFI PART","BEGIN IMMEDIATE","Unknown_Attribute","at most 16 retries","fallocate(PUNCH_HOLE)","ioctl(BLKDISCARD)","ioctl(BLKRRPART)","' is not a /dev block device node","NVMe critical warning bits are set after the run (0x","QD 8","controller/bridge, not the media","current state only and does not predict future reliability.","data was available to confirm it"}
guid = re.compile(r'^[0-9A-F]{8}-[0-9A-F]{4}-')

out = []
seen = set()
for s in cand:
    if s in seen: continue
    seen.add(s)
    if len(s) < 3 or s in skip_exact: continue
    if re.match(r'^[\s;:,)=<$\-\d(\[]', s) or 'excluded.' in s or s.startswith('request ['): continue   # fragments and non-prose
    if sql.search(s) or guid.match(s): continue
    if "%" in s or "\\" in s: continue
    if re.search(r'(\s|\(|\'|:|"|\.\.)$', s): continue          # fragments of larger messages / report labels
    if re.search(r'^(Create|Read|Write|Get|IOCTL|Flush)[A-Z_]', s) or s.startswith("IOCTL"): continue
    if not re.search(r'[A-Za-z]', s): continue
    if re.fullmatch(r'[a-z0-9_\-+/.]+', s) and " " not in s: continue   # machine identifiers: "fast", "gpt", "io_error"
    if re.fullmatch(r'[A-Z0-9_]+', s) and "_" in s: continue          # PARTITION_EDIT, SECURE_ERASE...
    out.append(s)

# Messages the core builds from several adjacent literals (so the scan above only sees halves).
out += [
    "Flash storage remaps and over-provisions blocks, so overwriting cannot reach every cell. For sensitive data use the drive's secure-erase / sanitize command or encryption.",
    "SMART reports PASSED, but no attribute or health-log data was available to confirm it",
    "No", "primary", "backup", "bootable", "SELF_TEST", "SECURE_ERASE", "SANITIZE", "POWER_MANAGEMENT", "PARTITION_EDIT", "RAW_SECTOR_ACCESS",
    "No adverse observations in the available SMART data. This describes the current state only and does not predict future reliability.",
]
out = sorted(set(out))
dst = root / "src/gui/i18n/core_phrases.cpp"
with dst.open("w", encoding="utf-8") as f:
    f.write("// SPDX-License-Identifier: TBD\n// GENERATED by tools/gen_core_phrases.py - do not edit by hand.\n//\n"
            "// Fixed phrases produced by the core libraries. They are listed here only so that lupdate\n"
            "// puts them in the translation file (context \"core\"); i18n::ct() looks them up at run time.\n"
            "#include <QtGlobal>\n\nnamespace platter::gui::i18n {\n\n"
            "[[maybe_unused]] static const char* const kCorePhrases[] = {\n")
    for s in out:
        f.write(f'    QT_TRANSLATE_NOOP("core", "{s}"),\n')
    f.write("};\n\n}  // namespace platter::gui::i18n\n")
print(len(out), "phrases ->", dst)
